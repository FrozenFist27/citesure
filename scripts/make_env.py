"""Create <project>/.env by copying ONLY the keys this project needs from the
root secrets.env. Never prints, logs or echoes any secret value.

Usage:  python scripts/make_env.py
"""

from __future__ import annotations

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SECRETS = PROJECT_ROOT.parent / "secrets.env"
TARGET = PROJECT_ROOT / ".env"

# Only the keys this project needs (per the workflow task).
WANTED = ("ANTHROPIC_API_KEY", "LLM_PROVIDER", "LLM_MODEL")

# Defaults applied after the copied keys (not secrets).
EXTRA_LINES = [
    "JUDGE_MODEL=claude-haiku-5-5",
    "DAILY_QUESTION_CAP=200",
    "RATE_LIMIT_PER_IP_PER_HOUR=10",
]


def parse_env(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        out[key.strip()] = value.strip().strip('"').strip("'")
    return out


def main() -> int:
    if not SECRETS.exists():
        print(f"ERROR: secrets file not found at {SECRETS}")
        return 1

    secrets = parse_env(SECRETS.read_text(encoding="utf-8"))

    missing = [k for k in WANTED if not secrets.get(k)]
    if missing:
        print(f"ERROR: missing required key(s) in secrets.env: {', '.join(missing)}")
        return 1

    lines = [
        "# Generated by scripts/make_env.py - do not commit (git-ignored).",
        "# Values copied from the workspace secrets file; never printed.",
        "",
    ]
    for key in WANTED:
        # NOTE: value is written to the file but never printed to stdout/stderr.
        lines.append(f"{key}={secrets[key]}")
    lines.extend(EXTRA_LINES)

    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {TARGET} with keys: {', '.join(WANTED)} (+ defaults). Values not shown.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
